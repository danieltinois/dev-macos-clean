// Regenerates core/cat-art.ts: the mascot's base drawing, converted to ASCII from a
// public-domain photo. Dev-only (needs network and macOS `sips`); the output is committed.
//
//   bun scripts/cat-art.ts
//
// Photo: "Domestic Cat White" by JMG2JMG, public domain, via Wikimedia Commons:
// https://commons.wikimedia.org/wiki/File:Domestic_Cat_White.JPG
import {execFileSync} from 'node:child_process';
import {mkdtempSync, readFileSync, rmSync, writeFileSync} from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const SOURCE = 'https://upload.wikimedia.org/wikipedia/commons/e/e0/Domestic_Cat_White.JPG';
const PAGE = 'https://commons.wikimedia.org/wiki/File:Domestic_Cat_White.JPG';
const OUT = path.resolve(import.meta.dirname, '..', 'core', 'cat-art.ts');
// Crop (photo pixels), output columns and tone settings, tuned for a dark UI.
const CROP = {x0: 20, y0: 15, x1: 830, y1: 1540}, COLUMNS = 54, CELL_ASPECT = 1.65;
const FORM = 2.6, DETAIL = 2.8, BASE = 0.58;
const RAMP = " .'`^,:;-~=+*xX#%@";

function readBmp(file: string) {
  const b = readFileSync(file), off = b.readUInt32LE(10), w = b.readInt32LE(18), hRaw = b.readInt32LE(22), bpp = b.readUInt16LE(28);
  const h = Math.abs(hRaw), stride = Math.ceil(w * bpp / 32) * 4, lum = new Float32Array(w * h);
  for (let y = 0; y < h; y++) {
    const row = hRaw > 0 ? h - 1 - y : y;
    for (let x = 0; x < w; x++) {const i = off + row * stride + x * (bpp / 8);lum[y * w + x] = (0.299 * b[i + 2]! + 0.587 * b[i + 1]! + 0.114 * b[i]!) / 255;}
  }
  return {w, h, lum};
}

const dir = mkdtempSync(path.join(os.tmpdir(), 'devclean-cat-'));
try {
  const response = await fetch(SOURCE, {headers: {'User-Agent': 'devclean-dev (https://github.com/danieltinois/dev-macos-clean)'}});
  if (!response.ok) throw new Error(`download failed: ${response.status}`);
  writeFileSync(path.join(dir, 'cat.jpg'), Buffer.from(await response.arrayBuffer()));
  execFileSync('sips', ['-s', 'format', 'bmp', path.join(dir, 'cat.jpg'), '--out', path.join(dir, 'cat.bmp')], {stdio: 'ignore'});
  const {w, h, lum} = readBmp(path.join(dir, 'cat.bmp'));

  // Box blur via an integral image.
  const blur = (src: Float32Array, r: number) => {
    const I = new Float64Array((w + 1) * (h + 1)), out = new Float32Array(w * h);
    for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) I[(y + 1) * (w + 1) + x + 1] = src[y * w + x]! + I[y * (w + 1) + x + 1]! + I[(y + 1) * (w + 1) + x]! - I[y * (w + 1) + x]!;
    for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
      const a = Math.max(0, x - r), b = Math.max(0, y - r), c = Math.min(w, x + r + 1), d = Math.min(h, y + r + 1);
      out[y * w + x] = (I[d * (w + 1) + c]! - I[b * (w + 1) + c]! - I[d * (w + 1) + a]! + I[b * (w + 1) + a]!) / ((c - a) * (d - b));
    }
    return out;
  };
  // Background: flood fill from the border through dark pixels (the cat is white).
  const soft = blur(lum, 3), bg = new Uint8Array(w * h), stack: number[] = [];
  for (let x = 0; x < w; x++) stack.push(x, (h - 1) * w + x);
  for (let y = 0; y < h; y++) stack.push(y * w, y * w + w - 1);
  for (const s of stack) bg[s] = soft[s]! < 0.45 ? 1 : 0;
  while (stack.length) {
    const i = stack.pop()!, x = i % w;
    if (!bg[i]) continue;
    for (const j of [i - 1, i + 1, i - w, i + w]) {
      if (j < 0 || j >= w * h || Math.abs((j % w) - x) > 1 || bg[j]) continue;
      if (soft[j]! < 0.45) {bg[j] = 1;stack.push(j);}
    }
  }
  // Flatten the flash falloff (white fur = uniform base) and keep form shading plus fine detail.
  const far = blur(lum, 70), near = blur(lum, 12);
  const tone = (i: number) => BASE + FORM * (near[i]! - far[i]!) + DETAIL * (lum[i]! - near[i]!);
  const cw = (CROP.x1 - CROP.x0) / COLUMNS, ch = cw * CELL_ASPECT, rows = Math.floor((CROP.y1 - CROP.y0) / ch);
  const lines: string[] = [];
  for (let r = 0; r < rows; r++) {
    let line = '';
    for (let c = 0; c < COLUMNS; c++) {
      let sum = 0, cat = 0, n = 0;
      for (let y = Math.floor(CROP.y0 + r * ch); y < CROP.y0 + (r + 1) * ch; y++) for (let x = Math.floor(CROP.x0 + c * cw); x < CROP.x0 + (c + 1) * cw; x++) {
        const i = y * w + x;sum += tone(i);cat += bg[i] ? 0 : 1;n++;
      }
      const coverage = cat / n;
      if (coverage < 0.45) {line += ' ';continue;}
      const level = Math.max(0, Math.min(1, sum / n)) * Math.min(1, coverage * 1.3);
      line += RAMP[Math.max(1, Math.min(RAMP.length - 1, Math.round(level * (RAMP.length - 1))))];
    }
    lines.push(line.trimEnd());
  }
  while (lines[0] === '') lines.shift();
  const art = lines.map(line => `  ${JSON.stringify(line)},`).join('\n');
  writeFileSync(OUT, `// Generated by scripts/cat-art.ts. Do not edit by hand.
// From "Domestic Cat White" by JMG2JMG (public domain), Wikimedia Commons:
// ${PAGE}
export const CAT_ART = [
${art}
];
`);
  console.log(`wrote ${path.relative(process.cwd(), OUT)} (${lines.length} rows)`);
} finally {
  rmSync(dir, {recursive: true, force: true});
}
